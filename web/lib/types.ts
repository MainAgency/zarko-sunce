/**
 * Hand-mirrored Payload types.
 *
 * Only the media collections live here for now — a type gets added per content
 * collection as it lands in the CMS.
 */

export interface MediaImageType {
  id: number;
  alt: string;
  caption?: string | null;
  prefix?: string | null;
  updatedAt: string;
  createdAt: string;
  url?: string | null;
  thumbnailURL?: string | null;
  filename?: string | null;
  mimeType?: string | null;
  filesize?: number | null;
  width?: number | null;
  height?: number | null;
  focalX?: number | null;
  focalY?: number | null;
}

